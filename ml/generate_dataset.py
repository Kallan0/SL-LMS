def _bend(joints, bends):
    """Apply per-joint offsets to a set of landmarks."""
    result = dict(joints)
    for idx, offset in bends.items():
        ox, oy, oz = offset
        bx, by, bz = result.get(idx, (0, 0, 0))
        result[idx] = (bx + ox, by + oy, bz + oz)
    return result


def _interpolate(joints, tip_idx, mid_idx, start, end, steps=4):
    """Interpolate finger joints from start to end position."""
    for i in range(steps):
        frac = (i + 1) / steps
        idx = tip_idx - (steps - 1 - i)
        base_x, base_y, base_z = joints.get(mid_idx, (0, 0, 0))
        joints[idx] = (
            base_x + (end[0] - base_x) * frac,
            base_y + (end[1] - base_y) * frac,
            base_z + (end[2] - base_z) * frac,
        )
    joints[tip_idx] = end
    return joints


