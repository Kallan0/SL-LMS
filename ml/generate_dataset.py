def _add_noise(joints: dict, std: float = NOISE_STD) -> np.ndarray:
    """Convert landmark dict to flat array with Gaussian noise."""
    coords = []
    for i in range(NUM_LANDMARKS):
        x, y, z = joints.get(i, (0.0, 0.0, 0.0))
        coords.extend([
            x + np.random.normal(0, std),
            y + np.random.normal(0, std),
            z + np.random.normal(0, std * 0.5),  # z has less variance
        ])
    return np.array(coords, dtype=np.float32)


def _random_transform(coords: np.ndarray) -> np.ndarray:
    """Apply random rotation, scaling, and translation to simulate variation."""
    # Random rotation around Z axis (in-plane rotation)
    angle = np.random.uniform(-0.3, 0.3)  # ~±17 degrees
    cos_a, sin_a = np.cos(angle), np.sin(angle)

    # Random scale
    scale = np.random.uniform(0.85, 1.15)

    # Random translation
    tx = np.random.uniform(-0.05, 0.05)
    ty = np.random.uniform(-0.05, 0.05)

    transformed = coords.copy()
    for i in range(NUM_LANDMARKS):
        idx = i * 3
        x, y = transformed[idx], transformed[idx + 1]
        # Scale + rotate
        nx = (x * cos_a - y * sin_a) * scale + tx
        ny = (x * sin_a + y * cos_a) * scale + ty
        transformed[idx] = nx
        transformed[idx + 1] = ny

    return transformed


def generate_dataset(output_path: str = None, samples_per_letter: int = SAMPLES_PER_LETTER):
    """Generate the full synthetic ISL dataset and save to CSV."""
    if output_path is None:
        output_path = os.path.join(os.path.dirname(__file__), "data", "isl_landmarks.csv")

    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    letters = sorted(LETTER_SHAPES.keys())
    rows = []

    print(f"Generating synthetic ISL dataset: {len(letters)} letters × {samples_per_letter} samples")

    for letter in letters:
        shape = LETTER_SHAPES[letter]
        for _ in range(samples_per_letter):
            # Generate noisy base landmarks
            right_hand = _add_noise(shape)

            # Apply random spatial transform
            right_hand = _random_transform(right_hand)

            # Clamp to [0, 1] range (MediaPipe normalized coords)
            right_hand = np.clip(right_hand, 0.0, 1.0)

            # Left hand is zero-padded (not visible in most ISL)
            left_hand = np.zeros(NUM_LANDMARKS * COORDS_PER_LANDMARK, dtype=np.float32)

            # Combine: right hand + left hand = 126 features
            sample = np.concatenate([right_hand, left_hand])
            rows.append([letter] + sample.tolist())

    # Write CSV
    header = ["label"] + [f"f{i}" for i in range(FEATURES_PER_SAMPLE)]

    with open(output_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(header)
        writer.writerows(rows)

    total = len(letters) * samples_per_letter
    print(f"Dataset saved to {output_path}")
    print(f"Total samples: {total} ({samples_per_letter} per letter)")
    print(f"Features per sample: {FEATURES_PER_SAMPLE}")
    return output_path


if __name__ == "__main__":
    generate_dataset()
